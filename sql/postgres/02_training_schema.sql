CREATE TABLE public.plan_adjustment_runs
(
    adjustment_run_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    plan_id INTEGER NOT NULL,

    completion_rate NUMERIC(6, 4) NOT NULL,
    threshold_rate NUMERIC(6, 4) NOT NULL,

    window_start_date DATE NOT NULL,
    window_end_date DATE NOT NULL,

    reduction_rate NUMERIC(6, 4) NOT NULL,
    increase_rate NUMERIC(6, 4),

    adjustment_type VARCHAR(20),
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL,

    created_at TIMESTAMPTZ(0) NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    applied_at TIMESTAMPTZ(0),

    CONSTRAINT fk_plan_adjustment_runs_plan
        FOREIGN KEY (plan_id)
        REFERENCES public.training_plans (plan_id),

    CONSTRAINT ck_plan_adjustment_runs_dates
        CHECK (window_end_date >= window_start_date),

    CONSTRAINT ck_plan_adjustment_runs_rates
        CHECK (
            completion_rate BETWEEN 0 AND 1
            AND threshold_rate BETWEEN 0 AND 1
            AND reduction_rate BETWEEN 0 AND 1
            AND (
                increase_rate IS NULL
                OR increase_rate BETWEEN 0 AND 1
            )
        ),

    CONSTRAINT ck_plan_adjustment_runs_type
        CHECK (
            adjustment_type IS NULL
            OR adjustment_type IN (
                'REDUCTION',
                'PROGRESSION'
            )
        ),

    CONSTRAINT ck_plan_adjustment_runs_status
        CHECK (
            status IN (
                'PREVIEW',
                'APPLIED',
                'ROLLED_BACK'
            )
        )
);

CREATE TABLE public.planned_workout_history
(
    planned_workout_history_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    adjustment_run_id BIGINT NOT NULL,
    planned_workout_id BIGINT NOT NULL,
    plan_id INTEGER NOT NULL,

    previous_scheduled_date DATE NOT NULL,
    previous_workout_type VARCHAR(30) NOT NULL,
    previous_workout_name VARCHAR(200) NOT NULL,

    previous_planned_distance_m INTEGER,
    previous_planned_duration_sec INTEGER,
    previous_target_pace_sec_per_km INTEGER,
    previous_target_heart_rate_min SMALLINT,
    previous_target_heart_rate_max SMALLINT,

    previous_priority_weight NUMERIC(4, 2),
    previous_status VARCHAR(20),
    previous_notes VARCHAR(1000),

    new_workout_name VARCHAR(200) NOT NULL,
    new_planned_distance_m INTEGER,
    new_planned_duration_sec INTEGER,
    new_target_pace_sec_per_km INTEGER,
    new_notes VARCHAR(1000),

    changed_at TIMESTAMPTZ(0) NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_planned_workout_history_run
        FOREIGN KEY (adjustment_run_id)
        REFERENCES public.plan_adjustment_runs (adjustment_run_id),

    CONSTRAINT fk_planned_workout_history_workout
        FOREIGN KEY (planned_workout_id)
        REFERENCES public.planned_workouts (planned_workout_id),

    CONSTRAINT fk_planned_workout_history_plan
        FOREIGN KEY (plan_id)
        REFERENCES public.training_plans (plan_id)
);

CREATE TABLE public.plan_adjustments
(
    adjustment_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    plan_id INTEGER NOT NULL,
    evaluation_date DATE NOT NULL,

    completion_rate NUMERIC(6, 4) NOT NULL,
    adjustment_type VARCHAR(30) NOT NULL,
    volume_change_percent NUMERIC(6, 2),

    recommendation VARCHAR(1000) NOT NULL,
    reason VARCHAR(1000) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    created_at TIMESTAMPTZ(0) NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_plan_adjustments_plan
        FOREIGN KEY (plan_id)
        REFERENCES public.training_plans (plan_id),

    CONSTRAINT ck_plan_adjustments_completion
        CHECK (completion_rate BETWEEN 0 AND 1),

    CONSTRAINT ck_plan_adjustments_type
        CHECK (
            adjustment_type IN (
                'KEEP',
                'REDUCE',
                'REPEAT_WEEK',
                'RECOVERY_WEEK',
                'INCREASE',
                'REVIEW'
            )
        ),

    CONSTRAINT ck_plan_adjustments_status
        CHECK (
            status IN (
                'PENDING',
                'ACCEPTED',
                'REJECTED',
                'APPLIED'
            )
        )
);

CREATE TABLE public.activity_reviews
(
    activity_id BIGINT PRIMARY KEY,
    review_status VARCHAR(20) NOT NULL,
    review_reason VARCHAR(500),

    reviewed_at TIMESTAMPTZ(0) NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_activity_reviews_activity
